/**
 * E.164 番号から国番号を取り出す。判定できない場合は null。
 *
 * 国番号はプレフィックスフリーなので、短いものから順に見て最初に一致したものが
 * 唯一の解になる。
 */
export function getCallingCode(e164: string): string | null {
  if (!e164.startsWith('+')) {
    return null;
  }

  const digits = e164.slice(1);
  for (let length = 1; length <= 3; length++) {
    const candidate = digits.slice(0, length);
    if (ASSIGNED_CALLING_CODES.has(candidate)) {
      return candidate;
    }
  }

  return null;
}

/** 割り当て済みの国番号か */
export function isAssignedCallingCode(code: string): boolean {
  return ASSIGNED_CALLING_CODES.has(code);
}
